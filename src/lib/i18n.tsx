const dicts = { en, pt };

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s: string = dicts[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function formatPrice(value: number, lang: Lang) {
  return new Intl.NumberFormat(lang === "pt" ? "pt-PT" : "en-IE", {
    style: "currency",
    currency: "EUR",
    maximumFractionDigits: 0,
  }).format(value);
}

export function formatDate(iso: string, lang: Lang, opts: Intl.DateTimeFormatOptions = { day: "numeric", month: "short", year: "numeric" }) {
  return new Intl.DateTimeFormat(lang === "pt" ? "pt-PT" : "en-GB", opts).format(new Date(iso));
}

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
  l: (v: L) => string;
  price: (n: number) => string;
  date: (iso: string, opts?: Intl.DateTimeFormatOptions) => string;
};

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = window.localStorage.getItem("ninho-lang");
    if (saved === "en" || saved === "pt") setLangState(saved);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang === "pt" ? "pt-PT" : "en";
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem("ninho-lang", l);
  }, []);
  const value: Ctx = {
    lang,
    setLang,
    t: (k, v) => translate(lang, k, v),
    l: (v) => v[lang],
    price: (n) => formatPrice(n, lang),
    date: (iso, o) => formatDate(iso, lang, o),
  };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useI18n outside provider");
  return c;
}
